"""Figures for SPAR_CROSSED_GUIDED_SELFPRED_v1.0. Measured values only; predictor identity is blue (Qwen) / orange (Mistral)."""

from __future__ import annotations

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from spar_dynamic.dice_crossed_guidance import config as C  # noqa: E402
from spar_dynamic.dice_recognition_logprob.analysis import INK, INK2, GRID  # noqa: E402

COL = {"qwen": "#2a78d6", "mistral": "#eb6834"}
TARGET_COL = "#52514e"
NAME = {"qwen": "Qwen3-32B", "mistral": "Mistral Small 3.2"}
FACES = C.FACES


def _style():
    plt.rcParams.update({"axes.edgecolor": INK2, "axes.labelcolor": INK, "xtick.color": INK2, "ytick.color": INK2,
                         "font.size": 8, "axes.spines.top": False, "axes.spines.right": False, "axes.grid": True,
                         "grid.color": GRID, "grid.linewidth": 0.6, "axes.axisbelow": True, "legend.frameon": False})


def fig_heatmap(summary: dict, out: Path):
    fig, axes = plt.subplots(1, 2, figsize=(7.2, 3.0))
    for ax, key, title in ((axes[0], "cells_AH_js", "Prediction (AH arm)"), (axes[1], "cells_AH_js_native", "Native policy (direct generation)")):
        m = np.array([[summary[key][f"{p}->{g}"]["mean"] for g in C.MODELS] for p in C.MODELS])
        vmax = max(summary["cells_AH_js"][k]["mean"] for k in summary["cells_AH_js"]) * 1.05
        ax.imshow(m, cmap="Blues", vmin=0, vmax=vmax)
        for i in range(2):
            for j in range(2):
                ax.text(j, i, f"{m[i, j]:.3f}", ha="center", va="center", color="white" if m[i, j] > vmax * 0.55 else INK, fontsize=9)
        ax.set_xticks([0, 1], [f"target\n{NAME[g]}" for g in C.MODELS])
        ax.set_yticks([0, 1], [f"predictor\n{NAME[p]}" for p in C.MODELS])
        ax.grid(False)
        ax.set_title(title, fontsize=8.5, loc="left", color=INK)
    fig.suptitle("Mean JS divergence (bits) from the target's own conditional distribution\nTier B, all conditions and positions",
                 fontsize=8.5, x=0.01, ha="left", color=INK)
    fig.tight_layout()
    fig.savefig(out / "fig1_selfcross_heatmap.png", dpi=200)
    plt.close(fig)


def fig_paired(rows: list, out: Path):
    fig, axes = plt.subplots(1, 2, figsize=(7.2, 3.2), sharey=True)
    for ax, g in zip(axes, C.MODELS):
        items = sorted({r["item_id"] for r in rows if r["tier"] == "B" and r["generator"] == g})
        val = {}
        for r in rows:
            if r["tier"] == "B" and r["generator"] == g and r["arm"] == "AH":
                val.setdefault((r["predictor"], r["item_id"]), []).append(r["js"])
        x = np.arange(len(items))
        for p in C.MODELS:
            ax.scatter(x, [np.mean(val[(p, i)]) for i in items], s=18, color=COL[p], label=f"predictor {NAME[p]}",
                       edgecolor="white", linewidth=0.6, zorder=3)
        for k, i in enumerate(items):
            ax.plot([k, k], [np.mean(val[("qwen", i)]), np.mean(val[("mistral", i)])], color=GRID, lw=1, zorder=2)
        ax.set_xticks(x, [i.split("-")[-1] for i in items], fontsize=6)
        ax.set_xlabel("target item")
        ax.set_title(f"Targets generated by {NAME[g]}", fontsize=8.5, loc="left", color=INK)
    axes[0].set_ylabel("mean JS to target (bits), AH")
    axes[0].legend(loc="upper left", fontsize=7)
    fig.tight_layout()
    fig.savefig(out / "fig2_paired_self_vs_cross.png", dpi=200)
    plt.close(fig)


def fig_contrasts(summary: dict, out: Path):
    e = summary["estimands"]
    lines = [("E1 self-advantage, prediction (AH, JS)", e["E1_selfadv_AH_js"]["interaction"]),
             ("   on Qwen targets", e["E1_selfadv_AH_js"]["self_adv_qwen_targets"]),
             ("   on Mistral targets", e["E1_selfadv_AH_js"]["self_adv_mistral_targets"]),
             ("E1 all 9 arms (JS)", e["E1_selfadv_allarms_js"]["interaction"]),
             ("E2 self-advantage, native policy (JS)", e["E2_selfadv_native_js"]["interaction"]),
             ("E3 identity DiD, T vs A (JS)", e["E3_identity_T_minus_A_js"]["DiD"]),
             ("E3 identity DiD, R vs A (JS)", e["E3_identity_R_minus_A_js"]["DiD"]),
             ("E5 fixed position 7", e["E5_fixed7_pos7_selfadv_js"]["interaction"]),
             ("E5 immediate next", e["E5_immediate_first_selfadv_js"]["interaction"]),
             ("E6 tempered target", e["E6_selfadv_AH_js_tempered"]["interaction"])]
    fig, ax = plt.subplots(figsize=(7.2, 3.6))
    y = np.arange(len(lines))[::-1]
    for yy, (lab, v) in zip(y, lines):
        ax.plot([v["lo"], v["hi"]], [yy, yy], color=INK2, lw=1.6, solid_capstyle="round")
        ax.scatter([v["est"]], [yy], s=26, color=COL["qwen"], zorder=3, edgecolor="white", linewidth=0.6)
        ax.text(1.0, yy, f"{v['est']:+.3f} [{v['lo']:+.3f}, {v['hi']:+.3f}]", transform=ax.get_yaxis_transform(),
                ha="left", va="center", fontsize=7, color=INK)
    ax.axvline(0, color=INK2, lw=0.8)
    ax.set_yticks(y, [l for l, _ in lines])
    ax.set_xlabel("bits (95% cluster-bootstrap CI). E1/E2/E5/E6: + = closer to own model. E3: - = identity cue helps own model more")
    ax.grid(axis="y", visible=False)
    fig.tight_layout(rect=(0, 0, 0.8, 1))
    fig.savefig(out / "fig3_contrasts.png", dpi=200)
    plt.close(fig)


def fig_by_condition(rows: list, out: Path):
    conds = list(C.CONDITIONS)
    fig, axes = plt.subplots(1, 2, figsize=(7.2, 3.0), sharey=True)
    for ax, g in zip(axes, C.MODELS):
        x = np.arange(len(conds))
        for p in C.MODELS:
            for metric, ls, lab in (("js", "-", "prediction"), ("js_native", ":", "native policy")):
                v = [np.mean([r[metric] for r in rows if r["tier"] == "B" and r["generator"] == g and r["predictor"] == p
                              and r["arm"] == "AH" and r["cond"] == c and r["window_index"] == 1]) for c in conds]
                ax.plot(x, v, ls, color=COL[p], lw=2, marker="o", ms=4, label=f"{NAME[p]}, {lab}")
        ax.set_xticks(x, [f"{c}\npos {C.CONDITIONS[c]['positions'][0]}" for c in conds])
        ax.set_title(f"Targets generated by {NAME[g]}", fontsize=8.5, loc="left", color=INK)
    axes[0].set_ylabel("mean JS at first scored position (bits), AH")
    axes[1].legend(fontsize=6.5, loc="upper right")
    fig.tight_layout()
    fig.savefig(out / "fig4_by_condition.png", dpi=200)
    plt.close(fig)


def fig_tier_a(rows: list, out: Path):
    fig, axes = plt.subplots(1, 2, figsize=(7.2, 2.8), sharey=True)
    for ax, g in zip(axes, C.MODELS):
        rs = {r["predictor"]: r for r in rows if r["item_id"] == f"A-{g}" and r["cond"] == "k3" and r["arm"] == "AH" and r["window_index"] == 1}
        series = [(f"target {NAME[g]} (direct generation)", TARGET_COL, [rs["qwen"][f"q{f}"] for f in FACES])] + \
                 [(f"predictor {NAME[p]}", COL[p], [rs[p][f"p{f}"] for f in FACES]) for p in C.MODELS]
        w = 0.8 / 3
        x = np.arange(6)
        for i, (lab, col, p) in enumerate(series):
            ax.bar(x - 0.4 + w * (i + 0.5), p, w - 0.03, color=col, label=lab)
        seq = rs["qwen"]["sequence"]
        ax.set_xticks(x, [str(f) for f in FACES])
        ax.set_xlabel(f"die face at position 4 (true: {rs['qwen']['true_face']})")
        ax.set_title(f"Tier A, {NAME[g]} greedy G `{seq}`, k3 AH", fontsize=8, loc="left", color=INK)
        ax.grid(axis="x", visible=False)
        ax.set_ylim(0, 1)
    axes[0].set_ylabel("six-face probability")
    axes[0].legend(fontsize=6.5, loc="upper left")
    fig.tight_layout()
    fig.savefig(out / "fig5_tierA_k3_position4.png", dpi=200)
    plt.close(fig)


def fig_rq1(rq1: list, out: Path):
    fig, axes = plt.subplots(1, 2, figsize=(7.2, 2.8), sharey=True)
    cols = {"G": TARGET_COL, "F": COL["qwen"], "Fanon": "#1baf7a"}
    for ax, m in zip(axes, C.MODELS):
        w = 0.8 / 3
        x = np.arange(6)
        for i, ins in enumerate(("G", "F", "Fanon")):
            r = next(r for r in rq1 if r["model"] == m and r["instruction"] == ins and r["position"] == 1)
            ax.bar(x - 0.4 + w * (i + 0.5), [r[f"p{f}"] for f in FACES], w - 0.03, color=cols[ins], label=ins)
        ax.set_xticks(x, [str(f) for f in FACES])
        ax.set_xlabel("die face at position 1")
        ax.set_title(f"{NAME[m]}: direct G vs hypothetical F / Fanon", fontsize=8.5, loc="left", color=INK)
        ax.grid(axis="x", visible=False)
        ax.set_ylim(0, 1)
    axes[0].set_ylabel("six-face probability")
    axes[0].legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(out / "fig6_rq1_first_roll.png", dpi=200)
    plt.close(fig)


def all_figures(rows: list, summary: dict, rq1: list, out: Path):
    out.mkdir(parents=True, exist_ok=True)
    _style()
    fig_heatmap(summary, out)
    fig_paired(rows, out)
    fig_contrasts(summary, out)
    fig_by_condition(rows, out)
    fig_tier_a(rows, out)
    fig_rq1(rq1, out)
