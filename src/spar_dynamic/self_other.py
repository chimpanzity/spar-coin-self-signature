"""Pilot 2 — SELF vs OTHER attribution of a single behavioral trajectory.

A Loula-Experiment-1 analogue: one anonymous 50-flip H/T sequence is shown to
a judge and the judge must decide whether it was generated by the same
underlying model as itself (SELF) or by a different model (OTHER).

Reuses the 60 source trajectories generated by the pilot-1 dynamic run.
Uses plain-text one-word responses (SELF or OTHER) rather than structured JSON.
"""

