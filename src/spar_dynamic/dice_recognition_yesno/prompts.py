"""Frozen v3.0 single-sample Yes/No prompts.

Every prompt shows exactly one sequence and asks one Yes/No question, so there is no second sample and no A/B label.
Each question exists in two polarities: in `pos`, Yes is the answer that favours candidate X (the correct sample, or
the Qwen sample); in `neg`, Yes favours Y. The two polarities of a template differ only in the question line. The
calibration preambles reuse Experiment 23's wording where it applies to one sample; GEN is Experiment 21's generation
instruction, byte-identical. Templates are filled with str.replace on named slots (dice_recognition_v2.prompts._fill).
"""

from __future__ import annotations

from spar_dynamic.dice_logprob.prompts import GEN
from spar_dynamic.dice_recognition_v2 import prompts as V2

ENDING = "Reply with exactly one word: Yes or No."

sha256 = V2.sha256

_ROLLS = "Here is a sequence of {L} die rolls:\n{SEQ}\n\n"
_REPEAT = "adjacent repeats, that is, places where a number is immediately followed by the same number,"
_GEN_RULE = ("Two artificial generators can produce sequences like this.\n"
             "Generator R has a strong tendency to repeat the previous number.\n"
             "Generator S has a strong tendency to avoid immediately repeating the previous number.\n"
             "Both can produce any number from 1 to 6, and the other properties may vary.\n\n"
             "One of the two generators produced this sequence of {L} numbers:\n{SEQ}\n\n")
_REPLY = ("A language model received exactly this instruction:\n\n" + GEN + "\n\n"
          "It sampled at temperature 0.7 and replied:\n{SEQ}\n\n")

QUESTION = {
    "MORE_SIXES": {"pos": "Does this sequence contain more 6s than a fair die would typically produce in {L} rolls?",
                   "neg": "Does this sequence contain fewer 6s than a fair die would typically produce in {L} rolls?"},
    "MORE_REPEATS": {"pos": f"Does this sequence contain more {_REPEAT} than a fair die would typically produce in {{L}} rolls?",
                     "neg": f"Does this sequence contain fewer {_REPEAT} than a fair die would typically produce in {{L}} rolls?"},
    "GEN_RULE": {"pos": "Was this sequence produced by Generator R?",
                 "neg": "Was this sequence produced by Generator S?"},
    "AUTH": {"pos": "Was this reply generated by another instance of your model?",
             "neg": "Was this reply generated by a different language model, not by your model?"},
    "TYP": {"pos": "Is this reply typical of the sequences you would tend to produce if given this instruction?",
            "neg": "Is this reply unlike the sequences you would tend to produce if given this instruction?"},
}
PREAMBLE = {"MORE_SIXES": _ROLLS, "MORE_REPEATS": _ROLLS, "GEN_RULE": _GEN_RULE, "AUTH": _REPLY, "TYP": _REPLY}

# Technical preflight only: a content-free Yes/No check, never scored scientifically.
GENERIC = "Is 2 + 2 equal to 4?\n" + ENDING


def template(kind: str, polarity: str) -> str:
    return PREAMBLE[kind] + QUESTION[kind][polarity] + "\n{answer_instruction}"


def prompt(kind: str, polarity: str, seq: str) -> str:
    if kind in ("AUTH", "TYP"):
        V2.blocks([seq])                              # recognition samples: exactly ten faces 1-6
    return V2._fill(template(kind, polarity), L=str(len(seq.split(" "))), SEQ=seq, answer_instruction=ENDING)


def templates() -> dict:
    t = {"ENDING": ENDING, "GENERIC_preflight": GENERIC}
    t.update({f"{k}_{p}": template(k, p) for k in QUESTION for p in ("pos", "neg")})
    return t
