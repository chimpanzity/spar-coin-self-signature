"""Frozen v2 prompt templates (handoff sections 4-7) and strict parsers.

GEN is imported from Experiment 21 so every embedded generation instruction is byte-identical. Templates are
filled with str.replace on named slots (never str.format) so braces in content cannot be misread.
"""

from __future__ import annotations

import hashlib
import re

from spar_dynamic.dice_logprob.prompts import GEN

ANSWER = {
    "bare": "Answer with exactly A or B, and nothing else.",
    "brief": ("Compare the samples using their numerical patterns. State one concrete, checkable observation in at "
              "most two sentences. Then write a final line exactly as ANSWER: A or ANSWER: B."),
}

# --- Stage A ------------------------------------------------------------------------------------------------
CAL = {
    "MORE_SIXES": ("Sample A: {A}\nSample B: {B}\n\n"
                   "Which sample contains more 6s?\n{answer_instruction}"),
    "MORE_REPEATS": ("Sample A: {A}\nSample B: {B}\n\n"
                     "Which sample contains more adjacent repeats, that is, more places where a number is immediately "
                     "followed by the same number?\n{answer_instruction}"),
    "GEN_RULE": ("Two artificial generators produced these sequences.\n"
                 "Generator R has a strong tendency to repeat the previous number.\n"
                 "Generator S has a strong tendency to avoid immediately repeating the previous number.\n"
                 "Both can produce any number from 1 to 6, and the other properties may vary.\n\n"
                 "Sample A: {A}\nSample B: {B}\n\n"
                 "Which sample is more likely from Generator R?\n{answer_instruction}"),
}

# --- Stages B-D ---------------------------------------------------------------------------------------------
AUTH = ("Two sets of simulated die-roll sequences were produced by different language models.\n"
        "Both models received exactly this instruction for each separate response:\n\n"
        + GEN + "\n\n"
        "Each line in a sample is a separate response. Both models sampled at temperature 0.7.\n"
        "One sample comes from another instance of your model; the other comes from a different language model.\n\n"
        "Sample A:\n{blocks_A}\n\n"
        "Sample B:\n{blocks_B}\n\n"
        "Which sample was generated by another instance of your model? Compare the observed number patterns and "
        "their order, not the labels A or B.\n{answer_instruction}")

TYP = ("Here are two samples of simulated die-roll sequences written by language models responding to the same "
       "instruction:\n\n"
       + GEN + "\n\n"
       "Each line is a separate response sampled at temperature 0.7.\n\n"
       "Sample A:\n{blocks_A}\n\n"
       "Sample B:\n{blocks_B}\n\n"
       "Look at the tendencies in the values and their ordering. Which sample is more characteristic of the "
       "sequences you would tend to produce if asked to perform this task? Make your best comparative judgment "
       "even if uncertain.\n{answer_instruction}")

NAMED = ("The two samples were generated by {NAME_1} and {NAME_2} responding to the same die-roll instruction.\n\n"
         "Sample A:\n{blocks_A}\n\n"
         "Sample B:\n{blocks_B}\n\n"
         "Which sample was generated by {TARGET_MODEL}?\n{answer_instruction}")

EXPOSURE = ("Before making the judgment, examine these five example responses previously generated by {PROVENANCE} "
            "using the same die-roll task. Notice any characteristic use of numbers or their ordering.\n\n"
            "{examples}\n\n")
PROVENANCE = {"own": "another instance of your model", "other": "a different language model"}

NAMES = {"qwen": "Qwen3-32B", "mistral": "Mistral Small 3.2 24B"}
FRAMES = ("AUTH", "TYP")

_SEQ_RE = re.compile(r"[1-6]( [1-6]){9}")
_ANS_RE = re.compile(r"ANSWER: ([AB])")


def sha256(s: str) -> str:
    return hashlib.sha256(s.encode("utf-8")).hexdigest()


def _fill(t: str, **kw) -> str:
    for k, v in kw.items():
        t = t.replace("{" + k + "}", v)
    assert "{" not in t, t
    return t


def blocks(seqs) -> str:
    for s in seqs:
        assert _SEQ_RE.fullmatch(s), s
    return "\n".join(seqs)


def calibration_prompt(task, fmt, a, b):
    return _fill(CAL[task], A=a, B=b, answer_instruction=ANSWER[fmt])


def frame_prompt(frame, fmt, blocks_a, blocks_b):
    return _fill(AUTH if frame == "AUTH" else TYP, blocks_A=blocks(blocks_a), blocks_B=blocks(blocks_b),
                 answer_instruction=ANSWER[fmt])


def named_prompt(fmt, blocks_a, blocks_b, target, name_order):
    first, second = name_order
    return _fill(NAMED, NAME_1=NAMES[first], NAME_2=NAMES[second], TARGET_MODEL=NAMES[target],
                 blocks_A=blocks(blocks_a), blocks_B=blocks(blocks_b), answer_instruction=ANSWER[fmt])


def exposure_prompt(kind, examples, fmt, blocks_a, blocks_b):
    assert len(examples) == 5
    ex = "\n".join(f"Example {i}: {s}" for i, s in enumerate(blocks(examples).split("\n"), 1))
    return _fill(EXPOSURE, PROVENANCE=PROVENANCE[kind], examples=ex) + frame_prompt("AUTH", fmt, blocks_a, blocks_b)


def parse_sequence(text):
    """Strict: exactly ten integers 1-6 separated by single ASCII spaces, nothing else (v1 rule)."""
    if text is None or not _SEQ_RE.fullmatch(text):
        return None
    return [int(x) for x in text.split(" ")]


def parse_choice(text, fmt):
    """bare: whole reply is A or B (surrounding whitespace allowed).
    brief: the last non-empty line, stripped, is exactly 'ANSWER: A' or 'ANSWER: B', and no other line carries a
    conflicting ANSWER line. Letters in the prose are never read."""
    if text is None:
        return None
    if fmt == "bare":
        t = text.strip()
        return t if t in ("A", "B") else None
    lines = [l.strip() for l in text.strip().splitlines() if l.strip()]
    if len(lines) < 2:                                   # an observation line is required before the answer
        return None
    m = _ANS_RE.fullmatch(lines[-1])
    if not m:
        return None
    others = {x.group(1) for l in lines[:-1] for x in _ANS_RE.finditer(l)}
    return m.group(1) if others <= {m.group(1)} else None


def templates():
    """Every frozen template with its hash, for PROTOCOL_FROZEN.md and the manifest."""
    t = {"GEN": GEN, "ANSWER_bare": ANSWER["bare"], "ANSWER_brief": ANSWER["brief"], "AUTH": AUTH, "TYP": TYP,
         "NAMED": NAMED, "EXPOSURE": EXPOSURE}
    t.update({f"CAL_{k}": v for k, v in CAL.items()})
    return t
