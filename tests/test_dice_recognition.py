def _held():
    return [dict(stimulus_id=f"{m}-{k:02d}", source=m, sequence=_seq(k, 0 if m == "qwen" else 3))
            for m in C.SOURCES for k in range(1, 21)]


def test_pairs_and_trials_counterbalanced_with_correct_truth():
    pairs = T.make_pairs(_held())
    assert len(pairs) == 20 and all(p["qwen_id"].startswith("qwen") and p["mistral_id"].startswith("mistral") for p in pairs)
    tr = T.make_trials(pairs)
    assert len(tr) == 240 and len({t["trial_id"] for t in tr}) == 240
    for t in tr:
        seq_of = {t["A_source"]: t["sequence_A"], t["B_source"]: t["sequence_B"]}
        assert {t["A_source"], t["B_source"]} == {"qwen", "mistral"}
        assert seq_of[t["target_source"]] == (t["sequence_A"] if t["correct"] == "A" else t["sequence_B"])
        if t["condition"] == "self":
            assert t["target_source"] == t["judge"]                 # self truth flips with the judge
    for j in C.SOURCES:
        for c in P.CONDITIONS:
            for p in pairs:
                o = {t["orientation"]: t["correct"] for t in tr if t["judge"] == j and t["condition"] == c and t["pair_id"] == p["pair_id"]}
                assert set(o) == {"QA", "MA"} and o["QA"] != o["MA"]   # reversal inverts the correct letter


def _responses(pairs, rule):
    out = []
    for t in T.make_trials(pairs):
        ch = rule(t)
        out.append(dict(t, choice=ch, valid=ch is not None, is_correct=(ch == t["correct"]) if ch else None))
    return out


def test_accuracy_pair_first_and_consistency():
    pairs = T.make_pairs(_held())
    # always answer "A": every pair gets one right, one wrong -> 0.5, never consistent
    s = A.summarise_judgments(_responses(pairs, lambda t: "A"), pairs, {p["pair_id"]: 1.0 for p in pairs})
    assert all(abs(s["point"][f"{j}|{c}"] - 0.5) < 1e-12 for j in C.SOURCES for c in P.CONDITIONS)
    assert s["per_cell"]["qwen|self"]["orientation_consistency"] == 0 and s["per_cell"]["qwen|self"]["A_rate"] == 1
    # always correct -> 1.0, consistent, and the named own-model advantage is 0 (both judges perfect)
    s = A.summarise_judgments(_responses(pairs, lambda t: t["correct"]), pairs, {p["pair_id"]: 1.0 for p in pairs})
    assert s["point"]["qwen|self"] == 1 and s["per_cell"]["mistral|named_qwen"]["orientation_consistency"] == 1
    assert s["point"]["own_model_advantage_named"] == 0
    # one invalid orientation: that pair is scored on the remaining one, not counted twice
    def rule(t):
        if t["pair_id"] == "P01" and t["orientation"] == "QA":
            return None
        return t["correct"]
    s = A.summarise_judgments(_responses(pairs, rule), pairs, {p["pair_id"]: 1.0 for p in pairs})
    assert s["point"]["qwen|self"] == 1 and s["per_cell"]["qwen|self"]["n_valid"] == 39


def test_own_model_advantage_formula_and_paired_bootstrap():
    pairs = T.make_pairs(_held())
    # each judge correct only about its own model under named questions
    def rule(t):
        if t["condition"].startswith("named"):
            return t["correct"] if t["target_source"] == t["judge"] else ("B" if t["correct"] == "A" else "A")
        return t["correct"]
    s = A.summarise_judgments(_responses(pairs, rule), pairs, {p["pair_id"]: 0.0 for p in pairs})
    assert s["point"]["own_model_advantage_named"] == 1.0
    lo, hi = s["ci95_pair_bootstrap"]["own_model_advantage_named"]
    assert lo == hi == 1.0                                              # same pairs resampled for every cell


