def test_cv_scaler_fit_within_folds(monkeypatch):
    sizes = []
    real_fit = K.StandardScaler.fit

    def spy(self, X, y=None, **kw):
        sizes.append(len(X))
        return real_fit(self, X, y, **kw)
    monkeypatch.setattr(K.StandardScaler, "fit", spy)
    rng = np.random.default_rng(0)
    X = rng.normal(size=(60, 9))
    y = np.array([1] * 30 + [0] * 30)
    X[y == 1, 0] += 2
    s = K.oof_scores(X, y, np.arange(60))
    assert not np.isnan(s).any() and sizes and max(sizes) < 60      # never fit on all data inside CV


def test_grouped_cv_keeps_identical_strings_together():
    from sklearn.model_selection import StratifiedGroupKFold
    y = np.array([1] * 30 + [0] * 30)
    g = np.arange(60); g[1] = g[0]; g[31] = g[0]                  # one group spans both labels
    for tr, te in StratifiedGroupKFold(n_splits=5, shuffle=True, random_state=1).split(np.zeros((60, 1)), y, g):
        assert not (set(g[tr]) & set(g[te]))


