def test_stage_transitions(tmp_path):
    with pytest.raises(SystemExit):
        G.check_gate("calibration", None)
    p = tmp_path / "g.json"
    p.write_text(json.dumps(dict(stage="preflight", overall="FAIL", epsilon=0.05)))
    with pytest.raises(SystemExit):
        G.check_gate("calibration", str(p))
    p.write_text(json.dumps(dict(stage="preflight", overall="PASS", epsilon=0.05)))
    assert G.check_gate("calibration", str(p))["epsilon"] == 0.05
    with pytest.raises(SystemExit):                                   # screen needs the calibration gate, not preflight
        G.check_gate("screen", str(p))
    p.write_text(json.dumps(dict(stage="calibration", overall="FAIL", epsilon=0.05)))
    with pytest.raises(SystemExit):
        G.check_gate("screen", str(p))
    p.write_text(json.dumps(dict(stage="calibration", overall="PASS", epsilon=0.05)))
    assert G.check_gate("screen", str(p))["overall"] == "PASS"
    assert G.check_gate("preflight", None) is None


