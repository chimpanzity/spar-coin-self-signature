def test_orientations_differ_only_by_swap(items, pairs):
    for t in ST.calibration_trials(items):
        other = "XB" if t["orientation"] == "XA" else "XA"
        twin = next(u for u in ST.calibration_trials(items) if u["unit_id"] == t["unit_id"] and u["orientation"] == other)
        assert twin["prompt"] == t["prompt"].replace(t["A"], "\0").replace(t["B"], t["A"]).replace("\0", t["B"])
        break
    tr = ST.screen_trials(pairs)
    assert len(tr) == 20 * 2 * (2 + 2)
    for t in tr:
        assert t["prompt_sha256"] == P.sha256(t["prompt"])
        q, m = next((p["qwen_seq"], p["mistral_seq"]) for p in pairs if p["pair_id"] == t["unit_id"])
        assert (t["A"], t["B"]) == ((q, m) if t["orientation"] == "XA" else (m, q))
        assert f"Sample A:\n{t['A']}\n\nSample B:\n{t['B']}\n" in t["prompt"]


