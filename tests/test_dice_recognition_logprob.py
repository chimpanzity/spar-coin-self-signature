# --------------------------------------------------------------------------------------------- scores --
def test_score_algebra():
    r = SC.pair_score(2.0, -1.0, 0.05)
    assert r["S_X"] == 1.5 and r["B_pair"] == 0.5 and r["pref_X_as_A"] == 2.0 and r["pref_X_as_B"] == 1.0
    assert r["outcome"] == "X" and r["both_orders_X"] and not r["orientation_sensitive"]
    assert math.isclose(r["sigmoid_S"], 1 / (1 + math.exp(-1.5)))


def test_constant_label_bias_cancels():
    """Logits favour A by the same amount whatever the contents: S = 0, B_pair = the bias."""
    r = SC.pair_score(3.7, 3.7, 0.05)
    assert r["S_X"] == 0 and r["B_pair"] == 3.7 and r["outcome"] == "indeterminate"
    assert r["orientation_sensitive"] and not r["both_orders_X"]


def test_content_preference_plus_bias():
    """X preferred by 1 nat in both orders on top of a +4 A bias: S recovers the preference, B the bias."""
    r = SC.pair_score(4 + 1, 4 - 1, 0.05)
    assert r["S_X"] == 1 and r["B_pair"] == 4
    assert r["outcome"] == "X" and not r["both_orders_X"]            # always A: X preferred in one order only


def test_ties_and_epsilon():
    assert SC.outcome(0.05, 0.05) == "indeterminate" and SC.outcome(-0.05, 0.05) == "indeterminate"
    assert SC.outcome(0.0501, 0.05) == "X" and SC.outcome(-0.0501, 0.05) == "Y"
    assert SC.epsilon_from_delta(0.0) == 0.05 and SC.epsilon_from_delta(0.1) == 0.2
    r = SC.pair_score(0.06, 0.04, 0.05)                               # S = 0.01: tie, never correct
    assert r["outcome"] == "indeterminate"


def _rec(kind, uid, o, d, name_order=None, A="1 2", B="3 4"):
    return dict(kind=kind, unit_id=uid, orientation=o, d=d, mass_AB=0.99, argmax_token="A" if d > 0 else "B",
                A=A if o == "XA" else B, B=B if o == "XA" else A, name_order=name_order)


def test_pair_records_join_and_errors():
    recs = [_rec("AUTH", "P01", "XA", 1.0), _rec("AUTH", "P01", "XB", 0.5)]
    rows = SC.pair_records(recs, 0.05)
    assert len(rows) == 1 and rows[0]["S_X"] == 0.25 and rows[0]["X"] == "1 2"
    assert rows[0]["greedy_picks_X_XA"] and not rows[0]["greedy_picks_X_XB"]
    with pytest.raises(ValueError):
        SC.pair_records(recs[:1], 0.05)
    with pytest.raises(ValueError):
        SC.pair_records(recs + [recs[0]], 0.05)
    named = [_rec("NAMED_QWEN", "P01", o, d, no) for no in ("QM", "MQ") for o, d in (("XA", 1.0), ("XB", -1.0))]
    assert len(SC.pair_records(named, 0.05)) == 2


def _cal_rows(n_correct, n_both, eps=0.1):
    rows = []
    for t in C.TASKS:
        for i in range(12):
            k = i < n_correct[t]
            both = i < min(n_both[t], n_correct[t])
            d_xy, d_yx = (1.0, -1.0) if both else (3.0, 2.0) if k else (-1.0, 1.0)
            rows.append(dict(kind=t, unit_id=f"{t}-{i}", **SC.pair_score(d_xy, d_yx, eps)))
    return rows


def test_calibration_gate_pass_and_each_failure():
    ok = SC.calibration_gate(_cal_rows({"GEN_RULE": 10, "MORE_SIXES": 10, "MORE_REPEATS": 9}, {t: 8 for t in C.TASKS}), 0.1)
    assert ok["total_correct"] == 29 and ok["both_orders_correct"] == 24 and ok["overall"] == "PASS"
    low_task = SC.calibration_gate(_cal_rows({"GEN_RULE": 12, "MORE_SIXES": 12, "MORE_REPEATS": 7},
                                              {"GEN_RULE": 9, "MORE_SIXES": 8, "MORE_REPEATS": 7}), 0.1)
    assert low_task["total_correct"] == 31 and low_task["both_orders_correct"] == 24 and low_task["overall"] == "FAIL"
    assert [k for k, v in low_task["criteria"].items() if not v] == ["MORE_REPEATS >= 8/12"]
    low_both = SC.calibration_gate(_cal_rows({t: 12 for t in C.TASKS}, {t: 7 for t in C.TASKS}), 0.1)
    assert low_both["both_orders_correct"] == 21 and low_both["overall"] == "FAIL"
    low_total = SC.calibration_gate(_cal_rows({"GEN_RULE": 10, "MORE_SIXES": 9, "MORE_REPEATS": 9}, {t: 8 for t in C.TASKS}), 0.1)
    assert low_total["total_correct"] == 28 and low_total["overall"] == "FAIL"
    with pytest.raises(ValueError):
        SC.calibration_gate(_cal_rows({t: 12 for t in C.TASKS}, {t: 12 for t in C.TASKS})[:-1], 0.1)


def _pre_records(first_tokens=("A", "B", "A", "B", "A"), tokenwise_shift=0.01, repeats=(0.0, 0.0, 0.0)):
    out = []
    ids = ["MORE_SIXES-01|XA", "MORE_SIXES-01|XB", "MORE_REPEATS-01|XA", "MORE_REPEATS-01|XB", None]
    for i, (tid, ft) in enumerate(zip(ids, first_tokens)):
        uid, o = tid.split("|") if tid else ("GENERIC", "XA")
        d = 1.0 if o == "XA" else -1.0
        out.append(dict(trial_id=f"pre|{tid or 'GENERIC'}", kind="GENERIC" if not tid else uid.rsplit("-", 1)[0], unit_id=uid,
                        orientation=o, d=d, mass_AB=0.99, argmax_token=ft, greedy_first_token=ft, greedy_text=ft,
                        diagnostic=dict(d=d + (tokenwise_shift if o == "XA" else 0)),
                        template_checks=dict(ends_with_empty_think=True, has_system_turn=False, n_user_turns=1,
                                             label_appends_single_token={"A": True, "B": True}),
                        **({"determinism_repeats": [d + x for x in repeats]} if i == 0 else {})))
    return out


def test_preflight_gate():
    env = dict(revision_match=True, gpu="A100")
    g = SC.preflight_gate(_pre_records(), env)
    assert g["overall"] == "PASS" and math.isclose(g["delta"], 0.005) and g["epsilon"] == 0.05
    g = SC.preflight_gate(_pre_records(tokenwise_shift=0.3), env)
    assert math.isclose(g["epsilon"], 0.3) and g["overall"] == "PASS"
    assert SC.preflight_gate(_pre_records(tokenwise_shift=1.2), env)["overall"] == "FAIL"     # epsilon 1.2
    assert SC.preflight_gate(_pre_records(first_tokens=("A", "\n", "A", " ", "B")), env)["overall"] == "FAIL"
    assert SC.preflight_gate(_pre_records(first_tokens=("A", "\n", "A", "B", "B")), env)["overall"] == "PASS"
    assert SC.preflight_gate(_pre_records(repeats=(0.0, 2e-3, 0.0)), env)["overall"] == "FAIL"
    assert SC.preflight_gate(_pre_records(), dict(env, revision_match=False))["overall"] == "FAIL"
    bad = _pre_records()
    bad[2]["template_checks"] = dict(bad[2]["template_checks"], ends_with_empty_think=False)
    assert SC.preflight_gate(bad, env)["overall"] == "FAIL"


