class _Tok:
    """Qwen3-like toy tokenizer: single-character labels A=32, B=33; ' A'=362, ' B'=425."""
    table = {"A": [32], "B": [33], " A": [362], " B": [425], "AB": [32, 33]}

    def encode(self, s, add_special_tokens=False):
        return self.table[s]

    def decode(self, ids):
        inv = {v[0]: k for k, v in self.table.items() if len(v) == 1}
        return "".join(inv.get(i, "?") for i in ids)


def test_label_ids_and_scores_from_logits():
    import torch
    tok = _Tok()
    lab = G.label_ids(tok)
    assert lab["A"]["id"] == 32 and lab["B"]["id"] == 33 and lab["A"]["space_id"] == 362
    tok.table["A"] = [32, 33]
    with pytest.raises(SystemExit):
        G.label_ids(tok)
    tok.table["A"] = [32]
    logits = torch.full((500,), -20.0)
    logits[32], logits[33] = 2.0, 1.0
    s = G.scores_from_logits(logits, lab, tok, top_n=3)
    assert math.isclose(s["d"], 1.0, abs_tol=1e-6) and math.isclose(s["z_A"] - s["z_B"], 1.0)
    assert 0.99 < s["mass_AB"] <= 1.0 and s["argmax_token"] == "A" and s["argmax_id"] == 32
    lp = torch.log_softmax(logits, -1)
    assert math.isclose(s["logp_A"], float(lp[32]), rel_tol=1e-6)
    assert math.isclose(math.exp(s["logp_A"]) + math.exp(s["logp_B"]), s["mass_AB"], rel_tol=1e-5)
